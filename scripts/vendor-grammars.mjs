#!/usr/bin/env node
// Refreshes the vendored tree-sitter grammar WASM files in grammars/.
//
// The grammar npm packages carry a native `install` script (node-gyp-build), so
// they are never installed as dependencies. Instead we `npm pack` the pinned
// tarballs, extract only the prebuilt .wasm files and their LICENSE, and record
// SHA-256 checksums in grammars/manifest.json (verified by the test suite).
//
// This is the only script in the repo that touches the network, and it only
// runs when a maintainer bumps a grammar version.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const PACKAGES = [
  { name: 'tree-sitter-typescript', version: '0.23.2', wasm: ['tree-sitter-typescript.wasm', 'tree-sitter-tsx.wasm'] },
  { name: 'tree-sitter-python', version: '0.25.0', wasm: ['tree-sitter-python.wasm'] },
];

const outDir = new URL('../grammars/', import.meta.url);
const tmp = mkdtempSync(join(tmpdir(), 'saidvsdid-grammars-'));
const manifest = { note: 'Generated by scripts/vendor-grammars.mjs. Do not edit by hand.', grammars: [] };

try {
  for (const pkg of PACKAGES) {
    const spec = `${pkg.name}@${pkg.version}`;
    const tarball = execFileSync('npm', ['pack', spec, '--silent', '--pack-destination', tmp], {
      encoding: 'utf8',
      shell: process.platform === 'win32',
    }).trim().split('\n').pop();
    const extractDir = join(tmp, pkg.name);
    mkdirSync(extractDir, { recursive: true });
    // Relative paths + cwd: GNU tar on Windows would read 'C:' as a remote host.
    execFileSync('tar', ['-xzf', join('..', tarball)], { cwd: extractDir });
    copyFileSync(join(extractDir, 'package', 'LICENSE'), new URL(`${pkg.name}.LICENSE`, outDir));
    for (const file of pkg.wasm) {
      copyFileSync(join(extractDir, 'package', file), new URL(file, outDir));
      const sha256 = createHash('sha256').update(readFileSync(new URL(file, outDir))).digest('hex');
      manifest.grammars.push({ file, package: pkg.name, version: pkg.version, sha256 });
      console.log(`${file}  ${spec}  ${sha256}`);
    }
  }
  writeFileSync(new URL('manifest.json', outDir), JSON.stringify(manifest, null, 2) + '\n');
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
